const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const norm = (s) => s.replace(/<[^>]+>/g, '').replace(/["״׳']/g, '').toLowerCase();
const faqEl = document.querySelector('[data-faq]');
const emptyEl = document.querySelector('[data-empty]');
const q = document.getElementById('q');

document.querySelector('[data-topics]').innerHTML = FAQ.map((s) =>
  `<a href="#${s.id}" class="h-topic"><span aria-hidden="true">${s.icon}</span>${esc(s.title)}</a>`).join('');

function render(filter = '') {
  const f = norm(filter.trim());
  let shown = 0;
  faqEl.innerHTML = FAQ.map((s) => {
    const items = s.items.filter((it) => !f || norm(it.q).includes(f) || norm(it.a).includes(f));
    shown += items.length;
    if (!items.length) return '';
    return `<section class="h-section" id="${s.id}" aria-labelledby="t-${s.id}">
      <h2 id="t-${s.id}"><span aria-hidden="true">${s.icon}</span>${esc(s.title)}</h2>
      ${items.map((it) => `<details class="h-q"${f ? ' open' : ''}><summary>${esc(it.q)}</summary><div class="h-a">${it.a}</div></details>`).join('')}
    </section>`;
  }).join('');
  emptyEl.hidden = shown > 0;
}

function openTopic() {
  const id = location.hash.slice(1);
  const sec = id && document.getElementById(id);
  if (!sec) return;
  sec.querySelectorAll('details').forEach((d) => { d.open = true; });
  sec.scrollIntoView({ block: 'start' });
  sec.classList.remove('flash'); void sec.offsetWidth; sec.classList.add('flash');
}

q.addEventListener('input', () => render(q.value));
window.addEventListener('hashchange', openTopic);
render();
openTopic();
